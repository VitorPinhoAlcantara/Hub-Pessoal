pub fn search(query: &str) -> Vec<&'static str> {
    let terms: Vec<String> = fold_text(query)
        .split_whitespace()
        .map(str::to_string)
        .collect();
    if terms.is_empty() {
        return Vec::new();
    }
    CATEGORIES
        .iter()
        .flat_map(|category| category.items.iter())
        .filter(|(_, words)| {
            let words = fold_text(words);
            terms.iter().all(|term| words.contains(term.as_str()))
        })
        .map(|(emoji, _)| *emoji)
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn search_ignores_accents_and_case() {
        assert!(search("CORAÇÃO").contains(&"❤️"));
        assert!(search("pizza").contains(&"🍕"));
        assert!(search("zzzz").is_empty());
        assert!(search("   ").is_empty());
    }

    #[test]
    fn every_category_has_items() {
        assert!(CATEGORIES.iter().all(|c| !c.items.is_empty()));
    }
}
